# Neutral type model: both emitters render these.


class T:
    """A resolved type: kind in {str,int,num,bool,list,map,json,ref,enum,union}; `optional` is nullability."""

    def __init__(self, kind: str, *, of: "T | None" = None, name: str | None = None, optional: bool = False,
                 note: str | None = None):
        self.kind, self.of, self.name, self.optional, self.note = kind, of, name, optional, note

    def opt(self) -> "T":
        return T(self.kind, of=self.of, name=self.name, optional=True, note=self.note)


def ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


class Spec:
    def __init__(self, raw: dict):
        self.schemas: dict[str, dict] = raw["components"]["schemas"]
        self.paths: dict[str, dict] = raw["paths"]
        self.used: set[str] = set()
        # discriminated unions: name -> (property, {value: schema name})
        self.unions: dict[str, tuple[str, dict[str, str]]] = {}
        self.union_of: dict[str, set[str]] = {}

    # -- types --------------------------------------------------------------------------------------------------
    def resolve(self, node: dict) -> T:
        if "$ref" in node:
            name = ref_name(node["$ref"])
            self.mark(name)
            target = self.schemas[name]
            return T("enum" if "enum" in target else "ref", name=name)
        if "anyOf" in node:
            options = node["anyOf"]
            non_null = [o for o in options if o.get("type") != "null"]
            nullable = len(non_null) != len(options)
            if len(non_null) == 1:
                t = self.resolve(non_null[0])
                return t.opt() if nullable else t
            t = T("json", note=" | ".join(self.describe(o) for o in non_null))
            return t.opt() if nullable else t
        if "oneOf" in node:
            disc = node.get("discriminator")
            if disc and disc.get("mapping"):
                mapping = {k: ref_name(v) for k, v in disc["mapping"].items()}
                for member in mapping.values():
                    self.mark(member)
                name = self.union_name(list(mapping.values()))
                self.unions[name] = (disc["propertyName"], mapping)
                for member in mapping.values():
                    self.union_of.setdefault(member, set()).add(name)
                return T("union", name=name)
            return T("json", note=" | ".join(self.describe(o) for o in node["oneOf"]))
        kind = node.get("type")
        if "const" in node or "enum" in node:
            return T("str") if kind in (None, "string") else self.resolve({"type": kind})
        if kind == "string":
            return T("str")
        if kind == "integer":
            return T("int")
        if kind == "number":
            return T("num")
        if kind == "boolean":
            return T("bool")
        if kind == "array":
            return T("list", of=self.resolve(node.get("items", {})))
        if kind == "object":
            addl = node.get("additionalProperties")
            if isinstance(addl, dict) and addl and ("type" in addl or "$ref" in addl):
                return T("map", of=self.resolve(addl))
            return T("json", note="object")
        return T("json")

    def describe(self, node: dict) -> str:
        if "$ref" in node:
            return ref_name(node["$ref"])
        return node.get("type", "any")

    def union_name(self, members: list[str]) -> str:
        prefix = members[0]
        for m in members[1:]:
            while not m.startswith(prefix):
                prefix = prefix[:-1]
        name = prefix.rstrip("_") or "Union"
        return name if name not in self.schemas else name + "Union"

    def mark(self, name: str) -> None:
        if name in self.used:
            return
        self.used.add(name)
        schema = self.schemas[name]
        for prop in schema.get("properties", {}).values():
            self.resolve(prop)

    # -- operations ---------------------------------------------------------------------------------------------
    def operations(self) -> list[dict]:
        ops = []
        for path, item in self.paths.items():
            if not path.startswith(PREFIX) or path.startswith(EXCLUDED_PREFIXES):
                continue
            for method, op in item.items():
                if method not in ("get", "post", "put", "patch", "delete"):
                    continue
                name = re.sub(r"_api_v2_.*$", "", op["operationId"])
                params = [p for p in op.get("parameters", []) if p["in"] in ("path", "query")]
                idem = any(p["in"] == "header" and p["name"] == "Idempotency-Key" for p in op.get("parameters", []))
                body = None
                content = op.get("requestBody", {}).get("content", {})
                if "application/json" in content:
                    body = self.resolve(content["application/json"]["schema"])
                    if not op["requestBody"].get("required", False):
                        body = body.opt()
                ops.append({
                    "name": camel(name),
                    "method": method.upper(),
                    "path": path[len(PREFIX):],
                    "summary": op.get("summary", ""),
                    "description": (op.get("description") or "").strip(),
                    "path_params": [(p["name"], self.resolve(p["schema"])) for p in params if p["in"] == "path"],
                    "query_params": [
                        (p["name"], self.resolve(p["schema"]) if p.get("required") else self.resolve(p["schema"]).opt())
                        for p in params if p["in"] == "query"
                    ],
                    "idempotent": idem,
                    "body": body,
                    "result": self.result_type(op),
                })
        return sorted(ops, key=lambda o: (o["path"], o["method"]))

    def result_type(self, op: dict) -> T:
        for code in sorted(op["responses"]):
            if not code.startswith("2"):
                continue
            content = op["responses"][code].get("content", {}).get("application/json")
            if not content:
                return T("json", optional=True)
            schema = content["schema"]
            if "$ref" in schema and ref_name(schema["$ref"]).startswith("Envelope"):
                envelope = self.schemas[ref_name(schema["$ref"])]
                return self.resolve(envelope["properties"]["data"])
            if "anyOf" in schema:  # an endpoint that returns one of several envelopes
                datas = [self.schemas[ref_name(o["$ref"])]["properties"]["data"] for o in schema["anyOf"] if "$ref" in o]
                for d in datas:
                    self.resolve(d)
                return T("json", note=" | ".join(self.describe(d) for d in datas))
            return self.resolve(schema)
        return T("json", optional=True)


# ----------------------------------------------------------------------------------------------------------------
# Naming


def camel(snake: str) -> str:
    parts = re.split(r"[_\-\s.]+", snake)
    head = parts[0][:1].lower() + parts[0][1:]
    out = head + "".join(p[:1].upper() + p[1:] for p in parts[1:] if p)
    return "_" + out if out[:1].isdigit() else out


def upper_snake(value: str) -> str:
    out = re.sub(r"[^A-Za-z0-9]+", "_", value).strip("_").upper()
    return "_" + out if (not out or out[:1].isdigit()) else out


def kt_ident(name: str) -> str:
    return f"`{name}`" if name in KOTLIN_KEYWORDS else name


def sw_ident(name: str) -> str:
    return f"`{name}`" if name in SWIFT_KEYWORDS else name


def doc_lines(text: str, indent: str) -> list[str]:
    text = (text or "").strip()
    if not text:
        return []
    lines = [ln.rstrip().replace("*/", "* /") for ln in text.splitlines()]
    return [f"{indent}/**"] + [f"{indent} * {ln}".rstrip() for ln in lines] + [f"{indent} */"]


def sw_doc_lines(text: str, indent: str) -> list[str]:
    text = (text or "").strip()
    return [f"{indent}/// {ln.rstrip()}".rstrip() for ln in text.splitlines()] if text else []


