# Kotlin


def kt_type(t: T) -> str:
    base = {
        "str": "String",
        "int": "Long",
        "num": "Double",
        "bool": "Boolean",
        "json": "JsonElement",
    }.get(t.kind)
    if base is None:
        if t.kind == "list":
            base = f"List<{kt_type(t.of)}>"
        elif t.kind == "map":
            base = f"Map<String, {kt_type(t.of)}>"
        else:
            base = t.name
    return base + ("?" if t.optional else "")


def kotlin_models(spec: Spec) -> str:
    out = [f"// {HEADER}", "@file:Suppress(\"unused\", \"SpellCheckingInspection\")", "", f"package {KOTLIN_PACKAGE}", "",
           "import kotlinx.serialization.KSerializer",
           "import kotlinx.serialization.SerialName",
           "import kotlinx.serialization.Serializable",
           "import kotlinx.serialization.json.JsonContentPolymorphicSerializer",
           "import kotlinx.serialization.json.JsonElement",
           "import kotlinx.serialization.json.jsonObject",
           "import kotlinx.serialization.json.jsonPrimitive",
           "import uz.elchi.app.api.LenientEnumSerializer",
           "import uz.elchi.app.api.WireEnum",
           ""]
    for name in sorted(spec.used):
        if name.startswith("Envelope"):
            continue
        schema = spec.schemas[name]
        if "enum" in schema:
            out += doc_lines(schema.get("description", ""), "")
            out.append(f"@Serializable(with = {name}.Serializer::class)")
            out.append(f"enum class {name}(override val value: String) : WireEnum {{")
            seen: set[str] = set()
            for v in schema["enum"]:
                case = upper_snake(str(v))
                while case in seen:
                    case += "_"
                seen.add(case)
                out.append(f"    {case}(\"{v}\"),")
            out.append("    /** A value this app version does not know yet. Never sent to the server. */")
            out.append("    UNKNOWN(\"\");")
            out.append("")
            out.append(f"    object Serializer : KSerializer<{name}> by LenientEnumSerializer(\"{name}\", entries, UNKNOWN, {{ it.value }})")
            out.append("}")
            out.append("")
            continue
        props = schema.get("properties", {})
        required = set(schema.get("required", []))
        out += doc_lines(schema.get("description", ""), "")
        supers = sorted(spec.union_of.get(name, ()))
        out.append("@Serializable")
        if not props:
            out.append(f"class {name}" + (f" : {', '.join(supers)}" if supers else ""))
            out.append("")
            continue
        out.append(f"data class {name}(")
        for prop, node in props.items():
            t = spec.resolve(node)
            if prop not in required:
                t = t.opt()
            text = node.get("description") or ""
            if t.note:
                text = (text + "\n" if text else "") + f"JSON: {t.note}"
            out += doc_lines(text, "    ")
            default = " = null" if t.optional else ""
            if "const" in node and not t.optional and t.kind == "str":
                default = f" = \"{node['const']}\""
            out.append(f"    @SerialName(\"{prop}\") val {kt_ident(camel(prop))}: {kt_type(t)}{default},")
        out.append(")" + (f" : {', '.join(supers)}" if supers else ""))
        out.append("")
    for union, (prop, mapping) in sorted(spec.unions.items()):
        out.append(f"/** One of {', '.join(sorted(set(mapping.values())))}, chosen by `{prop}`. */")
        out.append(f"@Serializable(with = {union}.Serializer::class)")
        out.append(f"sealed interface {union} {{")
        out.append(f"    object Serializer : JsonContentPolymorphicSerializer<{union}>({union}::class) {{")
        out.append("        override fun selectDeserializer(element: JsonElement) =")
        out.append(f"            when (val tag = element.jsonObject[\"{prop}\"]?.jsonPrimitive?.content) {{")
        for value, member in sorted(mapping.items()):
            out.append(f"                \"{value}\" -> {member}.serializer()")
        out.append(f"                else -> throw IllegalArgumentException(\"{union}: unknown {prop} '$tag'\")")
        out.append("            }")
        out.append("    }")
        out.append("}")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def kotlin_endpoints(ops: list[dict]) -> str:
    out = [f"// {HEADER}", "@file:Suppress(\"unused\")", "", f"package {KOTLIN_PACKAGE}", "",
           "import kotlinx.serialization.builtins.ListSerializer",
           "import kotlinx.serialization.builtins.MapSerializer",
           "import kotlinx.serialization.builtins.nullable",
           "import kotlinx.serialization.builtins.serializer",
           "import kotlinx.serialization.json.JsonElement",
           "import uz.elchi.app.api.ApiResult",
           "import uz.elchi.app.api.ApiTransport",
           "",
           "/** Every client/driver `/api/v2` endpoint. Commands take the idempotency key of the user action (ADR-0005). */",
           "class ElchiApi(private val transport: ApiTransport) {"]
    for op in ops:
        params: list[str] = []
        for name, t in op["path_params"]:
            params.append(f"{kt_ident(camel(name))}: {kt_type(t)}")
        if op["body"] is not None:
            params.append(f"body: {kt_type(op['body'])}" + (" = null" if op["body"].optional else ""))
        if op["idempotent"]:
            params.append("idempotencyKey: String")
        for name, t in op["query_params"]:
            params.append(f"{kt_ident(camel(name))}: {kt_type(t)}" + (" = null" if t.optional else ""))
        path = op["path"]
        for name, t in op["path_params"]:
            # An enum path segment must carry its wire value, not the Kotlin constant name.
            wire = ".value" if kt_type(t) not in ("String", "Int", "Long", "Boolean") else ""
            path = path.replace("{" + name + "}", "${" + camel(name) + wire + "}")
        query = ", ".join(f"\"{n}\" to {kt_ident(camel(n))}" for n, _ in op["query_params"])
        result = op["result"]
        text = op["summary"] + (("\n\n" + op["description"]) if op["description"] else "")
        if result.note:
            text += f"\n\nReturns JSON: {result.note}"
        out += doc_lines(text, "    ")
        out.append(f"    suspend fun {op['name']}({', '.join(params)}): ApiResult<{kt_type(result)}> =")
        body_arg = "null"
        if op["body"] is not None:
            present = T(op["body"].kind, of=op["body"].of, name=op["body"].name)  # encode the value, not the optional
            body_arg = f"body?.let {{ transport.encode({kt_serializer(present)}, it) }}" if op["body"].optional \
                else f"transport.encode({kt_serializer(present)}, body)"
        out.append(f"        transport.send(")
        out.append(f"            method = \"{op['method']}\",")
        out.append(f"            path = \"{path}\",")
        out.append(f"            query = listOf({query}),")
        out.append(f"            body = {body_arg},")
        out.append(f"            idempotencyKey = {'idempotencyKey' if op['idempotent'] else 'null'},")
        out.append(f"            result = {kt_serializer(result)},")
        out.append("        )")
        out.append("")
    out[-1] = "}"
    return "\n".join(out) + "\n"


def kt_serializer(t: T) -> str:
    if t.kind == "str":
        s = "String.serializer()"
    elif t.kind == "int":
        s = "Long.serializer()"
    elif t.kind == "num":
        s = "Double.serializer()"
    elif t.kind == "bool":
        s = "Boolean.serializer()"
    elif t.kind == "json":
        s = "JsonElement.serializer()"
    elif t.kind == "list":
        s = f"ListSerializer({kt_serializer(T(t.of.kind, of=t.of.of, name=t.of.name, optional=t.of.optional))})"
    elif t.kind == "map":
        s = f"MapSerializer(String.serializer(), {kt_serializer(t.of)})"
    elif t.kind == "union":
        s = f"{t.name}.Serializer"
    else:
        s = f"{t.name}.serializer()"
    return s + (".nullable" if t.optional else "")


