"""Generate the native apps' v2 API layer (models + endpoint functions) from the v2 OpenAPI contract.

    python3 scripts/gen_native_api.py            # writes android-app/ and ios-app/ generated sources
    python3 scripts/gen_native_api.py --check    # exit 3 if a generated file on disk is stale

Input is the same contract the web client generates from (ADR-0010 §4):
``mobile-app/src/api/generated/openapi-v2.json`` (refresh it with ``scripts/export_openapi.py``).

Why a dedicated generator instead of openapi-generator / swift-openapi-generator: the v2 schema uses a small,
regular subset of OpenAPI 3.1 (objects, ``X | null``, enums, consts, two discriminated unions), and one script
gives Kotlin and Swift the *same* reading of it. Rules both outputs follow:

- Only endpoints a client or driver can call are emitted (``/admin/*`` is staff-only), and only the models they reach.
- ``Envelope_*`` wrappers are not models: the runtime owns one generic envelope and endpoints return ``data``.
- Every enum has an ``unknown`` case: an app version lives on phones for months, a new server value must not crash it.
- Timestamps stay ISO strings (the UI formats them in ``Asia/Tashkent``); money stays integer ``*_minor``.
- A field outside ``required`` or nullable is optional with a ``null`` default.
- Unions without a discriminator (a handful, mostly legacy) are raw JSON, and the doc comment says what they can be.
"""

