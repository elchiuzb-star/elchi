# Swift


def sw_type(t: T) -> str:
    base = {"str": "String", "int": "Int", "num": "Double", "bool": "Bool", "json": "JSONValue"}.get(t.kind)
    if base is None:
        if t.kind == "list":
            base = f"[{sw_type(t.of)}]"
        elif t.kind == "map":
            base = f"[String: {sw_type(t.of)}]"
        else:
            base = t.name
    return base + ("?" if t.optional else "")


def swift_models(spec: Spec) -> str:
    out = [f"// {HEADER}", "// swiftlint:disable all", "", "import Foundation", ""]
    for name in sorted(spec.used):
        if name.startswith("Envelope"):
            continue
        schema = spec.schemas[name]
        if "enum" in schema:
            cases, seen = [], set()
            for v in schema["enum"]:
                case = camel(upper_snake(str(v)).lower())
                while case in seen:
                    case += "_"
                seen.add(case)
                cases.append((sw_ident(case), str(v)))
            out += sw_doc_lines(schema.get("description", ""), "")
            out.append(f"public enum {name}: WireEnum, CaseIterable {{")
            for case, _ in cases:
                out.append(f"    case {case}")
            out.append("    /// A value this app version does not know yet. Never sent to the server.")
            out.append("    case unknown(String)")
            out.append("")
            out.append(f"    public static var allCases: [{name}] {{ [{', '.join('.' + c for c, _ in cases)}] }}")
            out.append("")
            out.append("    public var rawValue: String {")
            out.append("        switch self {")
            for case, value in cases:
                out.append(f"        case .{case}: return \"{value}\"")
            out.append("        case .unknown(let value): return value")
            out.append("        }")
            out.append("    }")
            out.append("")
            out.append("    public init(from decoder: Decoder) throws {")
            out.append("        let value = try decoder.singleValueContainer().decode(String.self)")
            out.append("        switch value {")
            for case, value in cases:
                out.append(f"        case \"{value}\": self = .{case}")
            out.append("        default: self = .unknown(value)")
            out.append("        }")
            out.append("    }")
            out.append("")
            out.append("    public func encode(to encoder: Encoder) throws {")
            out.append("        var container = encoder.singleValueContainer()")
            out.append("        try container.encode(rawValue)")
            out.append("    }")
            out.append("}")
            out.append("")
            continue
        props = schema.get("properties", {})
        required = set(schema.get("required", []))
        out += sw_doc_lines(schema.get("description", ""), "")
        out.append(f"public struct {name}: Codable, Hashable, Sendable {{")
        fields = []
        for prop, node in props.items():
            t = spec.resolve(node)
            if prop not in required:
                t = t.opt()
            text = node.get("description") or ""
            if t.note:
                text = (text + "\n" if text else "") + f"JSON: {t.note}"
            out += sw_doc_lines(text, "    ")
            ident = sw_ident(camel(prop))
            out.append(f"    public var {ident}: {sw_type(t)}")
            fields.append((prop, ident, t, node))
        if fields:
            out.append("")
            params = []
            for prop, ident, t, node in fields:
                default = ""
                if t.optional:
                    default = " = nil"
                elif "const" in node and t.kind == "str":
                    default = f" = \"{node['const']}\""
                params.append(f"{ident}: {sw_type(t)}{default}")
            out.append(f"    public init({', '.join(params)}) {{")
            for _, ident, _, _ in fields:
                plain = ident.strip("`")
                out.append(f"        self.{plain} = {ident}")
            out.append("    }")
            out.append("")
            out.append("    enum CodingKeys: String, CodingKey {")
            for prop, ident, _, _ in fields:
                out.append(f"        case {ident} = \"{prop}\"")
            out.append("    }")
        else:
            out.append("    public init() {}")
        out.append("}")
        out.append("")
    for union, (prop, mapping) in sorted(spec.unions.items()):
        out.append(f"/// One of {', '.join(sorted(set(mapping.values())))}, chosen by `{prop}`.")
        out.append(f"public enum {union}: Codable, Hashable, Sendable {{")
        for value, member in sorted(mapping.items()):
            out.append(f"    case {sw_ident(camel(value))}({member})")
        out.append("")
        out.append("    private enum Tag: String, CodingKey { case tag = \"" + prop + "\" }")
        out.append("")
        out.append("    public init(from decoder: Decoder) throws {")
        out.append("        let tag = try decoder.container(keyedBy: Tag.self).decode(String.self, forKey: .tag)")
        out.append("        switch tag {")
        for value, member in sorted(mapping.items()):
            out.append(f"        case \"{value}\": self = .{sw_ident(camel(value))}(try {member}(from: decoder))")
        out.append(f"        default: throw DecodingError.dataCorrupted(.init(codingPath: decoder.codingPath, debugDescription: \"{union}: unknown {prop} \\(tag)\"))")
        out.append("        }")
        out.append("    }")
        out.append("")
        out.append("    public func encode(to encoder: Encoder) throws {")
        out.append("        switch self {")
        for value, _ in sorted(mapping.items()):
            out.append(f"        case .{sw_ident(camel(value))}(let value): try value.encode(to: encoder)")
        out.append("        }")
        out.append("    }")
        out.append("}")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def swift_endpoints(ops: list[dict]) -> str:
    out = [f"// {HEADER}", "// swiftlint:disable all", "", "import Foundation", "",
           "/// Every client/driver `/api/v2` endpoint. Commands take the idempotency key of the user action (ADR-0005).",
           "public struct ElchiAPI: Sendable {",
           "    let transport: APITransport",
           "",
           "    public init(transport: APITransport) {",
           "        self.transport = transport",
           "    }",
           ""]
    for op in ops:
        params: list[str] = []
        for name, t in op["path_params"]:
            params.append(f"{sw_ident(camel(name))}: {sw_type(t)}")
        if op["body"] is not None:
            params.append(f"body: {sw_type(op['body'])}" + (" = nil" if op["body"].optional else ""))
        if op["idempotent"]:
            params.append("idempotencyKey: String")
        for name, t in op["query_params"]:
            params.append(f"{sw_ident(camel(name))}: {sw_type(t)}" + (" = nil" if t.optional else ""))
        path = op["path"]
        for name, t in op["path_params"]:
            # An enum path segment must carry its wire value, not the Swift case name.
            wire = ".rawValue" if sw_type(t) not in ("String", "Int", "Int64", "Bool") else ""
            path = path.replace("{" + name + "}", "\\(" + camel(name) + wire + ")")
        query = ", ".join(f"(\"{n}\", {sw_ident(camel(n))})" for n, _ in op["query_params"])
        result = op["result"]
        text = op["summary"] + (("\n\n" + op["description"]) if op["description"] else "")
        if result.note:
            text += f"\n\nReturns JSON: {result.note}"
        out += sw_doc_lines(text, "    ")
        out.append(f"    public func {op['name']}({', '.join(params)}) async throws -> APIResult<{sw_type(result)}> {{")
        body_arg = "body" if op["body"] is not None else "Optional<JSONValue>.none"
        out.append("        try await transport.send(")
        out.append(f"            method: \"{op['method']}\",")
        out.append(f"            path: \"{path}\",")
        out.append(f"            query: [{query}],")
        out.append(f"            body: {body_arg},")
        out.append(f"            idempotencyKey: {'idempotencyKey' if op['idempotent'] else 'nil'},")
        out.append(f"            as: {sw_type(result)}.self")
        out.append("        )")
        out.append("    }")
        out.append("")
    out[-1] = "}"
    return "\n".join(out) + "\n"


# ----------------------------------------------------------------------------------------------------------------


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 3 if a generated file is stale")
    args = parser.parse_args(argv)

    spec = Spec(json.loads(SPEC.read_text(encoding="utf-8")))
    for transport_type in ("ApiWarning", "PageMeta", "ErrorBody"):  # the runtime's envelope parts
        spec.mark(transport_type)
    ops = spec.operations()
    files = {
        KOTLIN_OUT / "Models.kt": kotlin_models(spec),
        KOTLIN_OUT / "ElchiApi.kt": kotlin_endpoints(ops),
        SWIFT_OUT / "Models.swift": swift_models(spec),
        SWIFT_OUT / "ElchiAPI.swift": swift_endpoints(ops),
    }
    stale = []
    for path, text in files.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if stale:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
        return 3
    models = len([n for n in spec.used if not n.startswith("Envelope")])
    print(f"{len(ops)} endpoints, {models} models ({len(spec.unions)} discriminated unions)"
          + (" - up to date" if args.check else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
